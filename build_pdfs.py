def P(t, st='body'):
    return Paragraph(t, S[st])


def BUL(items, st='bul'):
    return [Paragraph(t, S[st], bulletText='•') for t in items]


def QUOTE(t):
    return Paragraph('«' + t + '»', S['quote']) if not t.startswith('«') else Paragraph(t, S['quote'])


def H1(t):
    return P(t, 'h1')


def H2(t):
    return P(t, 'h2')


def H3(t):
    return P(t, 'h3')


def TBL(header, rows, widths, align_right=None):
    data = [[Paragraph(h, S['th']) for h in header]]
    for r in rows:
        data.append([Paragraph(str(c), S['td']) for c in r])
    t = Table(data, colWidths=widths, repeatRows=1, hAlign='LEFT')
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), BG),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('GRID', (0, 0), (-1, -1), 0.45, LINE),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#FAFCFE')]),
    ]
    t.setStyle(TableStyle(style))
    return t


def IMG(path, max_w, max_h=None):
    w, h = ImageReader(path).getSize()
    iw = max_w
    ih = iw * h / w
    if max_h and ih > max_h:
        ih = max_h
        iw = ih * w / h
    im = Image(path, width=iw, height=ih)
    im.hAlign = 'CENTER'
    return im


def make_pdf(path, footer_text, story, first_page_header=None):
    doc = BaseDocTemplate(path, pagesize=A4,
                          leftMargin=1.6 * cm, rightMargin=1.6 * cm,
                          topMargin=1.5 * cm, bottomMargin=1.5 * cm,
                          title=footer_text, author='Hermes Agent (iiko)')
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id='n')

    def on_page(cv, d):
        cv.saveState()
        cv.setFont('DVS', 7)
        cv.setFillColor(GRAY)
        cv.drawString(doc.leftMargin, 0.85 * cm, footer_text)
        cv.drawRightString(A4[0] - doc.rightMargin, 0.85 * cm, 'стр. %d' % d.page)
        cv.setStrokeColor(LINE)
        cv.setLineWidth(0.5)
        cv.line(doc.leftMargin, 1.05 * cm, A4[0] - doc.rightMargin, 1.05 * cm)
        cv.restoreState()

    doc.addPageTemplates([PageTemplate(id='all', frames=[frame], onPage=on_page)])
    doc.build(story)


def title_block(title, subtitle, meta_lines):
    st = [P(title, 'title'), P(subtitle, 'subtitle'), Spacer(1, 4),
          HRFlowable(width='100%', thickness=1.2, color=ACCENT, spaceAfter=6)]
    st += [P(m, 'meta') for m in meta_lines]
    st.append(Spacer(1, 8))
    return st


